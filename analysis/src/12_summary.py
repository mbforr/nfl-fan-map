"""12 — Compile output/SUMMARY.md from the metric artifacts + report gate status.

Reads only the outputs of tasks 01-11 (regenerable, order-independent) and writes
the human-readable report the video scriptwriter consumes. File-gated sections
(fan-bar match, demographics) render as "pending" until their inputs are supplied.
Idempotent: regenerates cleanly on every run.
"""
from __future__ import annotations

import json

import pandas as pd

import common as c

M = c.METRICS


def _csv(name):
    p = M / name
    return pd.read_csv(p) if p.exists() else None


def _json(name):
    p = M / name
    return json.load(open(p)) if p.exists() else None


def pct(x):
    return f"{100 * x:.1f}%" if x is not None and pd.notna(x) else "—"


def main() -> None:
    args = c.get_args(__doc__)
    log = c.setup_logging("12_summary")

    totals = c.load_totals()
    meta = totals["meta"]
    val = _json("validation.json")
    spike = _json("packers_spike_summary.json")
    prespike = _csv("leaderboard_prespike.csv")
    full_lb = _csv("leaderboard_full.csv")
    diaspora = _csv("diaspora_index.csv")
    moran = _csv("morans_i_per_team.csv")
    vor = _csv("voronoi_confusion.csv")
    dist = _csv("distance_decay_summary.csv")
    intl = _csv("international_top_teams.csv")
    rust = _csv("rust_belt_in_sun_belt.csv")
    bar_match = _csv("fan_bar_match.csv")
    fans_pc = _csv("fans_per_capita.csv")

    # ----- Gate evaluation -----
    gates = []
    gates.append(("features match pipeline region count",
                  val and val["checks"]["features_match_totals"]["ok"]))
    gates.append(("internal counts consistent",
                  val and val["checks"]["counts_match_a_total"]["ok"]))
    gates.append(("unjoined gap < 1%",
                  val and val["checks"]["unjoined_aggregate_gap"]["ok"]))
    if spike:
        gates.append(("Packers spike incl. May 19-21",
                      len(spike["may_19_21_present"]) == 3))
    if diaspora is not None:
        rd = diaspora.set_index("team")["diaspora_pct_global"]
        gates.append(("Raiders most-diaspora (lowest home %)",
                      diaspora.iloc[0]["team"] == "Las Vegas Raiders"))
        gates.append(("Texans most home-loyal (highest home %)",
                      diaspora.iloc[-1]["team"] == "Houston Texans"))
    if moran is not None:
        n_sig = int((moran["p_sim"] < 0.05).sum())
        gates.append((f"Moran p<0.05 for >=25 teams (got {n_sig})", n_sig >= 25))
    gate_lines = "\n".join(
        f"- {'✅' if ok else '❌'} {name}" for name, ok in gates)
    all_ok = all(ok for _, ok in gates)

    def table(df, cols, n=10):
        d = df[cols].head(n)
        head = "| " + " | ".join(cols) + " |\n|" + "|".join(["---"] * len(cols)) + "|"
        body = "\n".join("| " + " | ".join(str(v) for v in row) + " |"
                         for row in d.itertuples(index=False))
        return head + "\n" + body

    L = []
    L.append("# NFL Fan Map — Analysis Summary\n")
    L.append("_Generated by `analysis/src/12_summary.py` from the pipeline outputs "
             "(0630 data run). Regenerable; do not hand-edit._\n")

    L.append("## Headline numbers\n")
    L.append(f"| Metric | Value |\n|---|---|")
    L.append(f"| Total responses (raw) | **{meta['total_rows']:,}** |")
    L.append(f"| Valid, geo-resolved responses | **{meta['valid_rows']:,}** |")
    L.append(f"| Mapped regions | **{meta['unique_regions']:,}** |")
    L.append(f"| On-map responses (joined) | **{val['checks']['unjoined_aggregate_gap']['on_map']:,}** |")
    L.append(f"| Teams | **{meta['a_categories']}** |")
    if intl is not None:
        L.append(f"| Countries with ≥50 responses | **{len(intl)}** |")
    if spike:
        L.append(f"| Packers share (full, IG-skewed) | **{pct(spike['packers_full_share'])}** |")
        L.append(f"| Packers share (pre-spike May 11–18) | **{pct(spike['packers_prespike_share'])}** |")
    L.append("\n> **Basis note:** the spike & leaderboards (task 02) use the **raw** "
             "survey rows; diaspora, Voronoi, Moran's I, distance-decay and the "
             "international cut use the **joined-region** aggregates (rows that "
             "couldn't resolve to a region are dropped — see the unjoined gap below).\n")

    L.append("## Validation gates\n")
    L.append(gate_lines + "\n")

    if spike:
        L.append("## Problem 1 — The data is lying to you (Packers IG spike)\n")
        L.append(f"Packers spike days (>15% of daily volume, ≥10 responses): "
                 f"**{len(spike['packers_spike_days'])}** days, including "
                 f"{', '.join(spike['may_19_21_present'])}.\n")
        if prespike is not None:
            L.append("**Pre-spike corrected leaderboard (May 11–18):**\n")
            pk = prespike.copy()
            pk["share"] = pk["share"].map(pct)
            L.append(table(pk, ["team", "share", "count"], 10) + "\n")

    if diaspora is not None:
        L.append("## Problem 3 — Diaspora index (home-state share of each fanbase)\n")
        d = diaspora.copy()
        d["global"] = d["diaspora_pct_global"].map(pct)
        d["us_only"] = d["diaspora_pct_us"].map(pct)
        L.append("_Global denominator reproduces the plan's leaderboard; US-only "
                 "denominator runs higher. Texans read lower on the global basis "
                 "because this run has 113 international Texans fans._\n")
        L.append("**Most diaspora (lowest home-state share):**\n")
        L.append(table(d, ["team", "home_state", "global", "us_only", "global_fans"], 5) + "\n")
        L.append("**Most home-loyal (highest home-state share):**\n")
        L.append(table(d.iloc[::-1], ["team", "home_state", "global", "us_only", "global_fans"], 5) + "\n")

    if vor is not None:
        overall = vor["own_team_fans"].sum() / vor["total_fans_in_cell"].sum()
        L.append("## Problem 5 — Voronoi (nearest-stadium) vs. actual fandom\n")
        L.append(f"Only **{pct(overall)}** of fans root for their nearest-stadium "
                 f"team — geography ≠ fandom. Best-predicted and worst-predicted cells:\n")
        v = vor.copy(); v["accuracy"] = v["accuracy"].map(pct)
        L.append(table(v, ["cell_team", "accuracy", "total_fans_in_cell", "top_actual_team"], 3) + "\n")
        L.append(table(v.iloc[::-1], ["cell_team", "accuracy", "total_fans_in_cell", "top_actual_team"], 3) + "\n")

    if moran is not None:
        L.append("## Hidden science — Moran's I (spatial clustering per fanbase)\n")
        n_sig = int((moran['p_sim'] < 0.05).sum())
        nb = int(moran['sig_bonferroni'].sum()) if 'sig_bonferroni' in moran else None
        L.append(f"All tested teams significant at p<0.05: **{n_sig}/{len(moran)}**"
                 + (f" ({nb} survive Bonferroni)." if nb is not None else ".") + "\n")
        L.append("_Note: count-based Moran's I measures corridor-density clustering. "
                 "The Texans top the diaspora index but sit mid-pack here (their few "
                 "fans cluster in TX metros surrounded by zero-count counties)._\n")
        L.append("**Most spatially clustered:**\n")
        L.append(table(moran, ["team", "moran_i", "p_sim", "n_fans_us"], 5) + "\n")
        L.append("**Most spatially dispersed:**\n")
        L.append(table(moran.iloc[::-1], ["team", "moran_i", "p_sim", "n_fans_us"], 5) + "\n")

    if dist is not None:
        L.append("## Hidden science — Distance-decay (median km from home stadium)\n")
        dd = dist[["team", "wmedian_km_us", "pct_within_100km_us"]].copy()
        dd["pct_within_100km_us"] = dd["pct_within_100km_us"].map(pct)
        L.append("**Most local:**\n")
        L.append(table(dd, ["team", "wmedian_km_us", "pct_within_100km_us"], 5) + "\n")
        L.append("**Most national:**\n")
        L.append(table(dd.iloc[::-1], ["team", "wmedian_km_us", "pct_within_100km_us"], 5) + "\n")

    if intl is not None:
        L.append("## Problem 4 — International standouts (top team per country, ≥50)\n")
        it = intl.copy(); it["top_share"] = it["top_share"].map(pct)
        L.append(table(it, ["country", "total", "top_team", "top_count", "top_share", "diversity_norm"], 12) + "\n")

    if rust is not None:
        L.append("## Problem 6 — Rust Belt diaspora in Sun Belt metros\n")
        L.append("Fan counts by rust-belt team × sun-belt metro (county-FIPS joins):\n")
        cols = [c0 for c0 in rust.columns if c0 not in ("_row_total",)]
        rr = rust[rust.iloc[:, 0] != "_col_total"]
        L.append(table(rr, cols[:8], len(rr)) + "\n")

    L.append("## Problem 6 (cont.) — Fan-bar match & migration\n")
    if bar_match is not None:
        L.append("**Fan-bar match rate** (survey found the bars):\n")
        L.append(table(bar_match, ["team", "matched", "bars", "match_rate"], 10) + "\n")
    else:
        L.append("- ⏳ **Fan-bar match**: pending — drop per-team bar CSVs in "
                 "`analysis/data/fan_bars/` and run tasks 08–09.\n")
    if fans_pc is not None:
        L.append("**Fans per 100k (top states):**\n")
        L.append(table(fans_pc, ["state", "fans", "population", "fans_per_100k"], 10) + "\n")
    else:
        L.append("- ⏳ **Demographics / fans-per-capita / migration**: pending — drop "
                 "`population_state.csv` / `migration_flows.csv` in "
                 "`analysis/data/census/` and run task 10.\n")

    L.append("## Methodology caveats\n")
    L.append("- **Self-selected sample.** Responses come from Matt's Instagram "
             "audience plus the Packers IG spike — not a random NFL-fan sample.\n")
    L.append(f"- **Unjoined gap.** {val['checks']['unjoined_aggregate_gap']['gap']} valid "
             f"responses ({pct(val['checks']['unjoined_aggregate_gap']['gap_pct'])}) "
             "resolved to a region key but matched no boundary feature; they're in "
             "the raw totals but not on the map.\n")
    L.append("- **US is county-level; state figures roll up county FIPS.** No re-normalization "
             "of the survey's messy state strings was needed — the JS pipeline already "
             "resolved US rows to counties via ZIP.\n")
    L.append("- **Home-state = current stadium's state** (Giants/Jets→NJ, Commanders→MD, "
             "Raiders→NV); relocations are why those teams read as high-diaspora.\n")
    L.append("- **Voronoi is continental US only** (AK/HI excluded; AK also breaks the "
             "antimeridian dissolve).\n")

    out = c.OUT / "SUMMARY.md"
    out.write_text("\n".join(L) + "\n")
    log.info("wrote %s", out.relative_to(c.REPO_ROOT))
    for name, ok in gates:
        log.info("%s %s", "PASS" if ok else "FAIL", name)
    log.info("ALL GATES %s", "PASS" if all_ok else "FAIL (see above)")
    if args.validate and not all_ok:
        raise SystemExit("gate check failed")


if __name__ == "__main__":
    main()
